 const recipe=JSON.parse(await zip.file('templates.json').async('string')),t=recipe.templates[0];
 assert.equal(t.slots.filter(s=>s.role==='body').length,2);
 assert(t.slots.filter(s=>s.role==='body').every(s=>s.rect[3]<438));
 assert.equal(t.slots.find(s=>s.role==='piece').fields.question,'A shared president question');
 assert(zip.file('assets/ote-horizontal-logo.png'));
 await page.locator('#import-status').evaluate(e=>e.textContent='Reloading recipe');
 await page.locator('#import-issue').setInputFiles({name:'recipe.zip',mimeType:'application/zip',buffer:await fs.readFile(await download.path())});
 await page.waitForFunction(()=>document.querySelector('#import-status').textContent.includes('2 articles imported'));
 await page.waitForFunction(()=>document.querySelector('#pieces-list textarea')?.value==='A shared president question');
 assert.equal(await page.locator('#selected-template').inputValue(),'story-2-none-columns');
