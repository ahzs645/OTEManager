/* Original desktop ExtendScript bridge. Run the script generated by adobe-validation.mjs.
 * Opens an IDML and writes a separate INDD. Never overwrites an existing artifact.
 * No hosted Adobe API or unattended service is implied by this desktop script. */
(function () {
    if (typeof OTE_ADOBE_REQUEST === "undefined") throw Error("Prepare this script with adobe-validation.mjs first.");
    var request = OTE_ADOBE_REQUEST;
    var source = File(request.idml), folder = Folder(request.output);
    var nativeFile = File(folder.fsName + "/validated.indd"), reportFile = File(folder.fsName + "/adobe-checks.json");
    if (!source.exists || !folder.exists) throw Error("Input IDML or output folder is missing.");
    if (oteFileSha256(source) !== request.artifactSha256) throw Error("Input IDML changed after preparation.");
    if (nativeFile.exists || reportFile.exists) throw Error("Output already exists. Use a new output folder to preserve prior work.");
    // A small JSON writer avoids reliance on JSON support in ExtendScript versions.
    function encode(value) {
        if (value === null) return "null";
        if (typeof value === "number") { if (!isFinite(value)) throw Error("Nonfinite report number"); return String(value); }
        if (typeof value === "boolean") return String(value);
        if (typeof value === "string") return '"' + value.replace(/["\\\x00-\x1f]/g, function (c) {
            if (c === '"') return '\\"'; if (c === "\\") return "\\\\";
            var h = c.charCodeAt(0).toString(16); return "\\u" + ("0000" + h).slice(-4);
        }) + '"';
        var parts = [], key, i;
        if (value instanceof Array) { for (i = 0; i < value.length; i++) parts.push(encode(value[i])); return "[" + parts.join(",") + "]"; }
        for (key in value) if (value.hasOwnProperty(key)) parts.push(encode(key) + ":" + encode(value[key]));
        return "{" + parts.join(",") + "}";
    }
    function iso(date) {
        function p(n) { return n < 10 ? "0" + n : String(n); }
        return date.getUTCFullYear() + "-" + p(date.getUTCMonth()+1) + "-" + p(date.getUTCDate()) + "T" + p(date.getUTCHours()) + ":" + p(date.getUTCMinutes()) + ":" + p(date.getUTCSeconds()) + "Z";
    }
    var document = null, oldUnits = app.scriptPreferences.measurementUnit, process = null;
    try {
        app.scriptPreferences.measurementUnit = MeasurementUnits.POINTS;
        document = app.open(source, false);
        document.recompose();
        var checks = { missingFonts: [], invalidLinks: [], oversetStories: [], lowResolutionImages: [],
            minImagePpi: request.profile.minImagePpi, pageCount: document.pages.length,
            pageWidthPoints: Number(document.documentPreferences.pageWidth),
            pageHeightPoints: Number(document.documentPreferences.pageHeight),
            bleedPoints: [Number(document.documentPreferences.documentBleedTopOffset), Number(document.documentPreferences.documentBleedBottomOffset), Number(document.documentPreferences.documentBleedInsideOrLeftOffset), Number(document.documentPreferences.documentBleedOutsideOrRightOffset)],
            preflightProfile: request.profile.preflightProfile, preflightErrors: 0,
            colorProfile: String(document.cmykProfile) };
        var i, item, ppi;
        for (i = 0; i < document.fonts.length; i++) { item = document.fonts[i]; if (item.status !== FontStatus.INSTALLED) checks.missingFonts.push(String(item.name)); }
        for (i = 0; i < document.links.length; i++) { item = document.links[i]; if (item.status !== LinkStatus.NORMAL) checks.invalidLinks.push(String(item.name)); }
        for (i = 0; i < document.stories.length; i++) { item = document.stories[i]; if (item.overflows) checks.oversetStories.push(String(item.id)); }
        for (i = 0; i < document.allGraphics.length; i++) {
            item = document.allGraphics[i];
            // Vector/PDF objects have no effectivePpi and are covered by the selected preflight profile.
            if (item.constructor.name === "Image") {
                ppi = item.effectivePpi;
                if (!(ppi && ppi.length === 2 && ppi[0] >= request.profile.minImagePpi && ppi[1] >= request.profile.minImagePpi))
                    checks.lowResolutionImages.push(String(item.id));
            }
        }
        var profile = app.preflightProfiles.itemByName(request.profile.preflightProfile);
        if (!profile.isValid) throw Error("Required InDesign preflight profile is not installed: " + request.profile.preflightProfile);
        process = app.preflightProcesses.add(document, profile);
        process.waitForProcess();
        var result = process.processResults;
        // Unknown DOM responses fail closed instead of pretending preflight succeeded.
        if (!(result instanceof Array) || typeof result[0] !== "number" || result[0] < 0 || result[0] !== Math.floor(result[0]))
            throw Error("This InDesign version returned an unsupported preflight result. Review the profile manually and adapt the bridge before importing evidence.");
        checks.preflightErrors = result[0];
        document.save(nativeFile);
        var report = { schemaVersion: "ote.adobe-validation.v1", inputSha256: request.inputSha256,
            artifactSha256: request.artifactSha256, nativeSha256: oteFileSha256(nativeFile), checkedAt: iso(new Date()),
            application: { name: "Adobe InDesign", version: String(app.version), platform: String($.os) },
            checks: checks, outputs: { native: nativeFile.fsName } };
        reportFile.encoding = "UTF-8";
        if (!reportFile.open("w")) throw Error("Could not create Adobe check report.");
        reportFile.write(encode(report)); reportFile.close();
        alert("Adobe check report saved. Run adobe-validation.mjs finalize to bind the report to native output bytes. Any reported errors still block release.");
    } finally {
        if (process && process.isValid) process.remove();
        if (document && document.isValid) document.close(SaveOptions.NO);
        app.scriptPreferences.measurementUnit = oldUnits;
    }
}());
